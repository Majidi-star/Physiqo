  static String get(BuildContext context, String key) {
    final locale = Localizations.localeOf(context);
    final langCode = locale.languageCode;
    final otherLangCode = langCode == 'fa' ? 'en' : 'fa';
    
    final langMap = _localizedValues[langCode] ?? _localizedValues['fa']!;
    final otherLangMap = _localizedValues[otherLangCode] ?? _localizedValues['fa']!;
    
    String? val = langMap[key];
    if (val == null || val == key) {
      val = otherLangMap[key];
    }
    
    return (val == null || val == key) ? key : val;
  }
